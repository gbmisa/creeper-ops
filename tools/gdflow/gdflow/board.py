"""Renders design/IDEAS.md, the human-readable idea board (generated; edit via the CLI)."""

ORDER = ["approved", "briefed", "built", "scored", "raw", "verified", "parked", "rejected"]
TITLES = {
    "approved": "Approved: ready for a brief",
    "briefed": "Briefed: being built",
    "built": "Built: waiting for human verification",
    "scored": "Scored: waiting for a decision",
    "raw": "Raw: not scored yet",
    "verified": "Shipped and verified",
    "parked": "Parked",
    "rejected": "Rejected",
}


def render(project, ideas):
    lines = [f"# Idea board: {project['project']}", "",
             "_Generated by `gdflow`; don't edit by hand. Source: `ideas.json`._", "",
             "Priority = (2·fun + 2·fit + novelty) / (cost + risk). "
             "Only an approver moves ideas to **approved** or **verified**.", ""]
    for state in ORDER:
        group = sorted((i for i in ideas if i["status"] == state),
                       key=lambda i: -(i["priority"] or 0))
        if not group:
            continue
        lines += [f"## {TITLES[state]} ({len(group)})", ""]
        if state in ("parked", "rejected", "verified"):
            for i in group:
                why = i["history"][-1]["why"] if i["history"] else ""
                lines.append(f"- **{i['id']}** {i['title']}" + (f": {why}" if why else ""))
            lines.append("")
            continue
        lines += ["| ID | Idea | Pillar | Fun | Fit | Nov | Cost | Risk | Prio |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for i in group:
            s = i["scores"] or {}
            cells = [s.get(k, "") for k in ("fun", "fit", "novelty", "cost", "risk")]
            title = i["title"] + (f" ([brief]({_rel(project, i['brief'])}))" if i["brief"] else "")
            lines.append(f"| {i['id']} | **{title}**<br>{i['pitch']} | {i['pillar']} | "
                         + " | ".join(str(c) for c in cells) + f" | {i['priority'] or ''} |")
        lines.append("")
    with open(project.design("IDEAS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def _rel(project, path):
    import os
    return os.path.relpath(project.path(path), project.design())
